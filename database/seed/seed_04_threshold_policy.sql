-- seed_04_threshold_policy.sql — 기본 판정 정책 (T-29 threshold_policy)
-- 명세서 V2.2 / 적용 순서 1 (seed_01·02는 V2.1에서, seed_03은 V2.0에서 삭제 — 번호는 재사용하지 않는다)
-- V2.2에서 policy_name·created_by·notify_max_per_hour 컬럼이 없어져 값 4개만 넣는다.
--
-- 가입한 사용자는 판정 정책을 반드시 가리킨다 (user_account.threshold_policy_id NOT NULL).
-- 백엔드는 가입 시 설정에 둔 기본값 4개로 이 행을 찾는다 (UK-03). 없으면 같은 값으로 새로 넣는다.
--   이 시드는 개발·시험 DB에서 바로 가입할 수 있게 미리 넣어 두는 것이다.
--
-- | 컬럼                | 값   | 근거                                   | 결정 주체 (DB-01 4장) |
-- |---------------------|------|----------------------------------------|----------------------|
-- | threshold           | 0.700| 확정 (2026-10-10) — 화면 자세 점수 30점. FE 기본값·「보통」 민감도·서버 판정과 같음 | 모델 |
-- | hold_seconds        | 3.0  | 임시 — REQ 10장 #4 초기값 3초 (후보 3~5초) | 모델 + PM |
-- | recover_seconds     | 3.0  | 임시 — FE 설정 범위 1~10초, 0.5 단위 안 (2026-10-06 2.0→3.0) | 모델 + PM |
-- | realert_seconds     | 60   | 임시 — FE 설정 범위 15~180초, 5 단위 안 (2026-10-06 30→60) | PM + FE |
--
-- 시간당 알림 상한은 V2.2에서 없앴다. 알림 빈도는 재알림 간격(realert_seconds)으로만 제한한다.
--
-- 값이 확정되면 이 행을 고치지 않는다. 판정 정책은 한 번 기록하면 바꾸지 않는다 (BR-65).
--   이미 세션이 이 행을 가리키고 있을 수 있기 때문이다.
--   확정값은 새 값 조합으로 새 행을 넣고(같은 시드에 행 추가 또는 백엔드가 첫 가입 때 생성),
--   백엔드 설정의 기본값 4개만 바꾼다. 이 행은 과거 세션의 판정 근거로 남는다.
--   (V2.2에서 행을 직접 고친 것은 모든 DB를 새로 만드는 변경이라서다.)
-- =====================================================================
SET NAMES utf8mb4;
USE posture_service;

INSERT INTO threshold_policy
  (threshold, hold_seconds, recover_seconds, realert_seconds, created_at)
VALUES
  (0.700, 3.0, 3.0, 60, '2026-10-02 00:00:00.000');
